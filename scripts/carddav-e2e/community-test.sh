#!/usr/bin/env bash
# Pinned, unmodified upstream CardDAV suite; writes ONLY the dedicated account B.
set -euo pipefail
umask 077
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
STATE="$ROOT/.carddav-task10"
fail() { echo "community-test: $*" >&2; exit 1; }
MODE="${1:-run}"
[ "$#" -le 1 ] && { [ "$MODE" = run ] || [ "$MODE" = --prepare-only ]; } || fail "usage: $0 [--prepare-only]"
[ "$(uname -s)" = Darwin ] && [ "$(uname -m)" = arm64 ] || fail "pinned runtime supports macOS ARM64 only"
[ -f "$STATE/env" ] || fail "missing dedicated harness env; see docs/carddav-community-testing.md"
# This is the local env generated by scripts/carddav-e2e/up.sh.
source "$STATE/env"
[ "${DB_NAME:-}" = kith_carddav_task10_e2e ] || fail "refusing database outside dedicated harness"
[ "${PORT:-}" = 4527 ] && [ "${PLAYWRIGHT_BASE_URL:-}" = http://127.0.0.1:4527 ] || fail "refusing non-dedicated endpoint"
for tool in git curl shasum tar python3 lsof pgrep; do command -v "$tool" >/dev/null || fail "missing $tool"; done
TESTER="$STATE/community-caldavtester"
CALENDAR="$STATE/community-pycalendar-upstream"
TESTER_SHA=bed21e5924275552c1561febc8203a9f194cf737
CALENDAR_SHA=a12dd4e1ce8822b022d4abf2cfe6cc93902ff03f
checkout() {
  local dir="$1" url="$2" revision="$3"
  if [ ! -d "$dir" ]; then
    git clone --quiet --no-checkout "$url" "$dir"
    git -C "$dir" checkout --quiet --detach "$revision"
  fi
  [ "$(git -C "$dir" remote get-url origin)" = "$url" ] || fail "unexpected origin: $dir"
  [ "$(git -C "$dir" rev-parse HEAD)" = "$revision" ] || fail "unexpected revision: $dir (will not reset it)"
  [ -z "$(git -C "$dir" status --porcelain --untracked-files=no)" ] || fail "tracked upstream modifications: $dir"
}
checkout "$TESTER" https://github.com/apple/ccs-caldavtester.git "$TESTER_SHA"
checkout "$CALENDAR" https://github.com/apple/ccs-pycalendar.git "$CALENDAR_SHA"
RUNTIME=pypy2.7-v8.0.1-macos_arm64
ARCHIVE="$STATE/$RUNTIME.tar.gz"
DIGEST=8d9f5d9b440bb4886df07f5e5038b87985e2b977dc048763d6699fa7b7186b19
if [ ! -f "$ARCHIVE" ]; then
  curl -fsSL --retry 2 "https://downloads.python.org/pypy/$RUNTIME.tar.gz" -o "$ARCHIVE.download"
  mv "$ARCHIVE.download" "$ARCHIVE"
fi
[ "$(shasum -a 256 "$ARCHIVE" | awk '{print $1}')" = "$DIGEST" ] || fail "PyPy checksum mismatch"
[ -x "$STATE/$RUNTIME/bin/pypy" ] || tar -xzf "$ARCHIVE" -C "$STATE"
PYTHON="$STATE/$RUNTIME/bin/pypy"
"$PYTHON" -c 'import sys; assert sys.version_info[:2] == (2,7); assert sys.pypy_version_info[:3] == (8,0,1)' || fail "unsupported cached PyPy runtime"
RUN="$STATE/community-results/$(date -u +%Y%m%dT%H%M%SZ)-$$"
mkdir -p "$RUN"
CONFIG="$RUN/serverinfo.xml"
# Only server configuration changes. Test XML, resource fixtures and engine stay upstream.
DAV_PASSWORD="${DAV_PASSWORD:-ValidP@ssword123!}" python3 -I - "$TESTER/scripts/server/serverinfo.xml" "$CONFIG" <<'PY'
import os, re, sys
import xml.etree.ElementTree as ET
root = ET.parse(sys.argv[1]).getroot()
for key, value in {'host':'127.0.0.1','nonsslport':'4527','authtype':'basic','waitcount':'2','waitdelay':'0.1','waitsuccess':'2'}.items():
    node = root.find(key)
    if node is None: node = ET.SubElement(root, key)
    node.text = value
for old in root.findall('features'): root.remove(old)
features = ET.SubElement(root, 'features')
for feature in ('carddav','current-user-principal','sync-report','well-known','ctag'):
    ET.SubElement(features, 'feature').text = feature
fixed = {'$root:':'/dav/', '$principalcollection:':'/dav/principals/'}
for substitution in root.iter('substitution'):
    key, value = substitution.find('key').text, substitution.find('value')
    if key in fixed: value.text = fixed[key]
    elif re.match(r'^\$(?:userid|publicuserid|useradmin|userapprentice|userproxy|i18nid)(?:%d)?:$', key): value.text = 'dav-other@carddav.test'
    elif re.match(r'^\$(?:pswd|publicpswd|i18npswd)', key): value.text = os.environ['DAV_PASSWORD']
    elif re.match(r'^\$(?:principal|principaluri)(?:%d|_admin):$', key): value.text = '/dav/principals/'
    elif key == '$principal%dnoslash:': value.text = '/dav/principals'
    elif key == '$addressbookhome%d:': value.text = '/dav/addressbooks'
    elif key == '$addressbookpath%d:': value.text = '/dav/addressbooks/default'
ET.ElementTree(root).write(sys.argv[2], encoding='utf-8', xml_declaration=True)
PY
# Validate the actual upstream expansion, including repeat-generated aliases.
(cd "$TESTER" && PYTHONPATH="$CALENDAR/src" PYTHONDONTWRITEBYTECODE=1 \
  DAV_PASSWORD="${DAV_PASSWORD:-ValidP@ssword123!}" "$PYTHON" - "$CONFIG" <<'PY'
import os, sys
import xml.etree.ElementTree as ET
from src.serverinfo import serverinfo
info = serverinfo()
info.parseXML(ET.parse(sys.argv[1]).getroot())
expected = {
    '$userid1:': 'dav-other@carddav.test',
    '$pswd1:': os.environ['DAV_PASSWORD'],
    '$principal1:': '/dav/principals/',
    '$principaluri1:': '/dav/principals/',
    '$addressbookhome1:': '/dav/addressbooks',
    '$addressbookpath1:': '/dav/addressbooks/default',
}
for key, value in expected.items():
    assert info.subsdict.get(key) == value, 'Unsafe or missing substitution: ' + key
print('Upstream parser validated account B credentials and paths.')
PY
)
printf 'Pinned upstream and local configuration prepared: %s\n' "$RUN"
[ "$MODE" = --prepare-only ] && exit 0
[ -f "$STATE/server.pid" ] || fail "no dedicated server pid file"
SERVER_PID="$(cat "$STATE/server.pid")"
[[ "$SERVER_PID" =~ ^[0-9]+$ ]] || fail "invalid dedicated server pid"
kill -0 "$SERVER_PID" 2>/dev/null || fail "dedicated server is not running"
LISTENER="$(lsof -tiTCP:4527 -sTCP:LISTEN 2>/dev/null || true)"
if [ "$LISTENER" != "$SERVER_PID" ]; then
  [ -n "$LISTENER" ] && pgrep -P "$SERVER_PID" | grep -qx "$LISTENER" || fail "port 4527 listener is not the dedicated server"
fi
# Read-only authenticated check before any suite writes. Credentials stay off argv.
printf 'user = "dav-other@carddav.test:%s"\n' "${DAV_PASSWORD:-ValidP@ssword123!}" > "$RUN/curl.cfg"
curl -fsS -K "$RUN/curl.cfg" -X PROPFIND -H 'Depth: 0' http://127.0.0.1:4527/dav/addressbooks/default/ -o /dev/null
rm "$RUN/curl.cfg"
echo "Running unmodified upstream CardDAV suite against account B (writes/deletes fixture resources)."
set +e
(cd "$TESTER" && PYTHONPATH="$CALENDAR/src" PYTHONDONTWRITEBYTECODE=1 "$PYTHON" testcaldav.py \
  -s "$CONFIG" --all --subdir CardDAV --observer log --observer jsondump --print-details-onfail) > "$RUN/upstream.log" 2>&1
STATUS=$?
set -e
# The upstream JSON observer emits its document as one line on stdout; retain
# the complete original output and extract JSON without altering any results.
set +e
python3 -I - "$RUN/upstream.log" "$RUN/results.json" <<'PY'
import json, sys
result = None
with open(sys.argv[1]) as stream:
    for line in stream:
        if line.startswith('[{'):
            try: result = json.loads(line)
            except ValueError: pass
if result is None:
    print('No upstream JSON document; inspect upstream.log', file=sys.stderr)
    sys.exit(1)
with open(sys.argv[2], 'w') as stream: json.dump(result, stream, indent=2)
counts = [0,0,0,0]
def visit(node):
    if node.get('result') in range(4): counts[node['result']] += 1
    for child in node.get('tests', []): visit(child)
for node in result: visit(node)
print('Upstream results: passed=%d failed=%d errors=%d ignored=%d' % tuple(counts))
PY
SUMMARY_STATUS=$?
set -e
echo "Upstream exit: $STATUS; artifacts: $RUN"
[ "$STATUS" -eq 0 ] || exit "$STATUS"
exit "$SUMMARY_STATUS"
